# --------------------------------------------------------------------------
# helpers
# --------------------------------------------------------------------------
run_logged() {
  # Stream to the terminal and to the install log at the same time.
  set -o pipefail
  "$@" 2>&1 | sed 's/^/      /' | tee -a "${LOG_FILE}"
}

generate_password() {
  # Harbor demands >=8 chars with upper, lower and a digit.
  printf 'Hb%sA1' "$(openssl rand -base64 18 | tr -dc 'A-Za-z0-9' | cut -c1-16)"
}

# --------------------------------------------------------------------------
# stage: inventory
# --------------------------------------------------------------------------
write_inventory() {
  mkdir -p "${STATE_DIR}" "${OUTPUT_DIR}/logs"
  chmod 700 "${STATE_DIR}"

  # With a VIP, every published service hangs off it instead of node 1, so the
  # registry keeps working when the machine that first served it is down.
  # HARBOR_URL, DEMO_IMAGE_REF, registries.yaml and the pull secret are all
  # derived from HARBOR_HOST, so this one line moves all of them.
  if [[ -n "${VIP_ADDRESS}" ]]; then
    HARBOR_HOST="${VIP_ADDRESS}"
    CLUSTER_ENDPOINT="${VIP_ADDRESS}"
  else
    HARBOR_HOST="${NODE_IPS[0]}"
    CLUSTER_ENDPOINT="${NODE_IPS[0]}"
  fi
  HARBOR_URL="http://${HARBOR_HOST}:${HARBOR_NODEPORT}"
  DEMO_IMAGE_REF="${HARBOR_HOST}:${HARBOR_NODEPORT}/${HARBOR_PROJECT}/${DEMO_IMAGE_NAME}:${DEMO_IMAGE_TAG}"

  # Passwords are passed through the environment, never written to disk.
  export INSTALLER_SSH_PASSWORD="${SSH_PASSWORD}"
  export INSTALLER_BECOME_PASSWORD="${BECOME_PASSWORD}"

  {
    echo "---"
    echo "# generated by the airgapped installer - all nodes are servers, so the"
    echo "# cluster runs embedded etcd and survives losing one machine."
    echo "k3s_cluster:"
    echo "  children:"
    echo "    server:"
    echo "      hosts:"
    local ip
    for ip in "${NODE_IPS[@]}"; do echo "        ${ip}:"; done
    echo "    agent:"
    echo "      hosts: {}"
    echo "  vars:"
    echo "    ansible_user: ${SSH_USER}"
    echo "    ansible_port: ${SSH_PORT}"
    echo "    ansible_password: \"{{ lookup('env', 'INSTALLER_SSH_PASSWORD') }}\""
    echo "    ansible_become: true"
    echo "    ansible_become_method: ansible.builtin.sudo"
    echo "    ansible_become_password: \"{{ lookup('env', 'INSTALLER_BECOME_PASSWORD') }}\""
    echo "    ansible_ssh_common_args: '-o PreferredAuthentications=password,keyboard-interactive,publickey'"
  } > "${STATE_DIR}/inventory.yml"
  chmod 600 "${STATE_DIR}/inventory.yml"

  resolve_cluster_token

  {
    echo "---"
    echo "k3s_version: \"${K3S_VERSION}\""
    echo "target_arch: \"${TARGET_ARCH}\""
    echo "token: \"${K3S_TOKEN}\""
    echo "api_endpoint: \"${NODE_IPS[0]}\""
    echo "cluster_context: \"${CLUSTER_NAME}\""
    echo "airgap_dir: \"${AIRGAP_K3S_DIR}\""
    echo "manage_firewall: true"
    echo "kubeconfig_endpoint: \"${CLUSTER_ENDPOINT}\""
    echo "vip_address: \"${VIP_ADDRESS}\""
    echo "server_config_yaml: |"
    echo "  write-kubeconfig-mode: \"0600\""
    echo "  secrets-encryption: true"
    if [[ -n "${VIP_ADDRESS}" ]]; then
      # The k3s_server role merges this over its own config with combine(), so a
      # tls-san list here REPLACES the one it derives from api_endpoint. Node 1
      # must therefore appear in our list too, or the API certificate silently
      # loses the name the other servers join through.
      echo "  tls-san:"
      echo "    - \"${NODE_IPS[0]}\""
      echo "    - \"${VIP_ADDRESS}\""
    fi
    echo "registries_config_yaml: |"
    echo "  mirrors:"
    echo "    \"${HARBOR_HOST}:${HARBOR_NODEPORT}\":"
    echo "      endpoint:"
    echo "        - \"${HARBOR_URL}\""
    if [[ -n "${VIP_ADDRESS}" ]]; then
      # The prereq role copies these onto every server before k3s first starts,
      # so k3s applies kube-vip as soon as its API is up. Rendered in
      # render_kube_vip(), which runs before the k3s install.
      echo "extra_manifests:"
      echo "  - \"${STATE_DIR}/manifests/kube-vip.yaml\""
    fi
    # Escape hatches for site-specific k3s flags, e.g. extra --tls-san entries.
    if [[ -n "${K3S_EXTRA_SERVER_ARGS:-}" ]]; then
      echo "extra_server_args: \"${K3S_EXTRA_SERVER_ARGS}\""
    fi
    if [[ -n "${K3S_EXTRA_AGENT_ARGS:-}" ]]; then
      echo "extra_agent_args: \"${K3S_EXTRA_AGENT_ARGS}\""
    fi
  } > "${STATE_DIR}/vars.yml"
  chmod 600 "${STATE_DIR}/vars.yml"

  ok "inventory written for ${#NODE_IPS[@]} node(s)"
  dim "k3s ${K3S_VERSION} · airgap bundle ${AIRGAP_K3S_DIR}"
}

# The cluster token encrypts k3s's bootstrap data, so it has to be the SAME on
# every run. Minting a fresh one against an existing cluster does not start a
# new cluster - it stops the old one dead with
#   "bootstrap data already found and encrypted with different token"
# on all three servers at once.
#
# So: reuse the token this output directory recorded; failing that, recover the
# real one from a running node; only mint a new token when there is genuinely no
# cluster to join.
resolve_cluster_token() {
  local token_file="${OUTPUT_DIR}/cluster-token"

  if [[ -s "${token_file}" ]]; then
    K3S_TOKEN="$(tr -d '\r\n' < "${token_file}")"
    dim "reusing the cluster token from ${token_file}"
    return 0
  fi

  # No record here, but the nodes may already be a cluster - ask them.
  # Pick the token out by shape rather than by line number: the raw module wraps
  # the output in a host header, an ssh known-hosts warning and a "Shared
  # connection closed" line, and which of those appear varies.
  local existing
  existing="$(ansible "${NODE_IPS[0]}" -i "${STATE_DIR}/inventory.yml" -m raw \
                -a 'cat /var/lib/rancher/k3s/server/token 2>/dev/null' 2>/dev/null \
              | grep -oE 'K10[A-Za-z0-9:._-]+' | head -n1 || true)"

  if [[ -n "${existing}" ]]; then
    K3S_TOKEN="${existing}"
    warn "recovered the existing cluster token from ${NODE_IPS[0]}"
    dim "a new token would have broken the running cluster"
  else
    K3S_TOKEN="$(openssl rand -hex 32)"
    dim "no existing cluster found - generating a new cluster token"
  fi

  umask 077
  printf '%s\n' "${K3S_TOKEN}" > "${token_file}"
  umask 022
}

# --------------------------------------------------------------------------
# stage: connectivity
# --------------------------------------------------------------------------
check_connectivity() {
  local attempt=0 max=3 out rc
  while true; do
    attempt=$((attempt + 1))
    set +e
    out="$(ansible k3s_cluster -m raw -a 'command -v python3 || echo NO_PYTHON3' 2>&1)"
    rc=$?
    set -e
    echo "${out}" >> "${LOG_FILE}"

    if (( rc == 0 )) && ! grep -q NO_PYTHON3 <<< "${out}"; then
      ok "all ${#NODE_IPS[@]} node(s) reachable over SSH with python3 present"
      return 0
    fi

    if grep -q NO_PYTHON3 <<< "${out}"; then
      die "a node has no python3, which Ansible needs. Install python3 on every node
      (apt-get install python3) and run the installer again."
    fi

    if grep -qiE 'permission denied|invalid/incorrect password|authentication failure' <<< "${out}"; then
      warn "authentication failed"
      if (( attempt >= max )) || [[ -n "${K3S_NODE_IPS:-}" ]] || ! have_tty; then
        die "could not authenticate to the nodes as '${SSH_USER}' after ${attempt} attempt(s)."
      fi
      ask_secret SSH_PASSWORD "Password for ${SSH_USER}@<node>"
      [[ "${SSH_USER}" == "root" ]] && BECOME_PASSWORD="${SSH_PASSWORD}"
      export INSTALLER_SSH_PASSWORD="${SSH_PASSWORD}"
      export INSTALLER_BECOME_PASSWORD="${BECOME_PASSWORD}"
      continue
    fi

    printf '%s\n' "${out}" | sed 's/^/      /' >&2
    die "could not reach every node over SSH on port ${SSH_PORT}. See the output above."
  done
}

