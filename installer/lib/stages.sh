install_longhorn() {
  local chart
  chart="$(find "${AIRGAP_LONGHORN_DIR}" -name 'longhorn-*.tgz' -print -quit)"
  [[ -n "${chart}" ]] || die "no Longhorn chart found in ${AIRGAP_LONGHORN_DIR}"

  local ui_args=()
  if [[ -n "${LONGHORN_UI_NODEPORT}" ]]; then
    ui_args=(--set "service.ui.type=NodePort" --set "service.ui.nodePort=${LONGHORN_UI_NODEPORT}")
  fi

  info "installing $(basename "${chart}") - images come from the local containerd store"
  run_logged helm upgrade --install longhorn "${chart}" \
    --namespace "${LONGHORN_NAMESPACE}" --create-namespace \
    --values /opt/longhorn/values-base.yaml \
    --set "defaultSettings.defaultDataPath=${LONGHORN_DATA_PATH}" \
    --set "defaultSettings.defaultReplicaCount=${LONGHORN_REPLICA_COUNT}" \
    --set "persistence.defaultClassReplicaCount=${LONGHORN_REPLICA_COUNT}" \
    --set "persistence.defaultClass=${LONGHORN_DEFAULT_STORAGE_CLASS}" \
    "${ui_args[@]}" \
    --wait --timeout 20m \
    || die "Longhorn did not become ready. Inspect: kubectl -n ${LONGHORN_NAMESPACE} get pods"

  # helm --wait only proves the pods are up. Longhorn is not actually usable
  # until its own node objects report the disks as schedulable.
  info "waiting for Longhorn to accept every node's disk"
  local deadline=$((SECONDS + 600)) ready=0 total="${#NODE_IPS[@]}"
  while (( SECONDS < deadline )); do
    ready="$(kubectl -n "${LONGHORN_NAMESPACE}" get nodes.longhorn.io \
              -o jsonpath='{range .items[*]}{.status.conditions[?(@.type=="Schedulable")].status}{"\n"}{end}' \
              2>/dev/null | grep -c '^True$' || true)"
    (( ready >= total )) && break
    sleep 10
  done
  (( ready >= total )) || die "only ${ready}/${total} nodes offered storage to Longhorn.
      Check: kubectl -n ${LONGHORN_NAMESPACE} get nodes.longhorn.io -o wide"
  ok "${ready}/${total} nodes contributing storage"

  if [[ "${LONGHORN_DEFAULT_STORAGE_CLASS}" == "true" ]]; then
    set_longhorn_default
  fi

  kubectl get storageclass 2>&1 | sed 's/^/      /' | tee -a "${LOG_FILE}"

  if [[ -n "${LONGHORN_UI_NODEPORT}" ]]; then
    ok "Longhorn UI on http://${NODE_IPS[0]}:${LONGHORN_UI_NODEPORT} (no authentication)"
  else
    dim "UI: kubectl -n ${LONGHORN_NAMESPACE} port-forward svc/longhorn-frontend 8080:80"
  fi
}

# --------------------------------------------------------------------------
# stage: Harbor
# --------------------------------------------------------------------------
# Two StorageClasses both claiming to be default is a real failure mode: which
# one a PVC gets is then arbitrary. Demote k3s's local-path and prove exactly
# one default remains. local-path stays usable by name.
set_longhorn_default() {
  # k3s re-applies its bundled manifests every time a server starts, which puts
  # the default-class annotation straight back on local-path. Annotating alone
  # therefore lasts only until the next reboot, and the cluster is then left
  # with *two* classes claiming to be default - so a PVC that names none gets an
  # arbitrary one.
  #
  # A .skip file tells k3s to stop re-applying that one manifest. The
  # StorageClass and its provisioner are left exactly as they are, so local-path
  # keeps working by name; k3s simply stops overwriting our change. The cost is
  # that a k3s upgrade will no longer refresh the local-path provisioner - delete
  # the .skip file if you want that back.
  run_logged ansible k3s_cluster -i "${STATE_DIR}/inventory.yml" \
    -m ansible.builtin.file \
    -a "path=/var/lib/rancher/k3s/server/manifests/local-storage.yaml.skip state=touch mode=0644" \
    || warn "could not pin the local-storage addon - local-path may reclaim the default class on reboot"

  if kubectl get storageclass local-path >/dev/null 2>&1; then
    run_logged kubectl annotate storageclass local-path \
      storageclass.kubernetes.io/is-default-class=false --overwrite \
      || warn "could not demote the local-path StorageClass"
  fi

  local defaults
  defaults="$(kubectl get storageclass -o json 2>/dev/null \
    | jq -r '.items[]
             | select(.metadata.annotations["storageclass.kubernetes.io/is-default-class"] == "true")
             | .metadata.name' | sort | tr '\n' ' ' | sed 's/ $//')"

  if [[ "${defaults}" != "longhorn" ]]; then
    die "expected 'longhorn' to be the only default StorageClass, got: ${defaults:-none}.
      Check: kubectl get storageclass"
  fi
  ok "longhorn is the default StorageClass (local-path kept, not default)"
}

# Which StorageClass Harbor's volumes land on. A PVC's class is immutable once
# bound, so an existing Harbor keeps whatever it already has - otherwise the
# helm upgrade would just fail with a confusing error.
harbor_storage_class() {
  if [[ -n "${HARBOR_STORAGE_CLASS}" ]]; then
    printf '%s' "${HARBOR_STORAGE_CLASS}"; return 0
  fi
  local existing
  existing="$(kubectl -n "${HARBOR_NAMESPACE}" get pvc harbor-registry \
                -o jsonpath='{.spec.storageClassName}' 2>/dev/null || true)"
  if [[ -n "${existing}" ]]; then
    printf '%s' "${existing}"; return 0
  fi
  if kubectl get storageclass longhorn >/dev/null 2>&1; then
    printf 'longhorn'; return 0
  fi
  printf 'local-path'
}

install_harbor() {
  local chart
  chart="$(find "${AIRGAP_HARBOR_DIR}" -name 'harbor-*.tgz' -print -quit)"
  [[ -n "${chart}" ]] || die "no Harbor chart found in ${AIRGAP_HARBOR_DIR}"

  # Reuse the password on re-runs so pull secrets stay valid.
  if kubectl -n "${HARBOR_NAMESPACE}" get secret harbor-core >/dev/null 2>&1; then
    HARBOR_ADMIN_PASSWORD="$(kubectl -n "${HARBOR_NAMESPACE}" get secret harbor-core \
      -o jsonpath='{.data.HARBOR_ADMIN_PASSWORD}' | base64 -d)"
    dim "reusing the existing Harbor admin password"
  else
    HARBOR_ADMIN_PASSWORD="$(generate_password)"
  fi

  HARBOR_SC="$(harbor_storage_class)"
  info "installing $(basename "${chart}") on the '${HARBOR_SC}' StorageClass"
  dim "images come from the local containerd store"
  run_logged helm upgrade --install harbor "${chart}" \
    --namespace "${HARBOR_NAMESPACE}" --create-namespace \
    --values /opt/harbor/values-base.yaml \
    --set "persistence.persistentVolumeClaim.registry.storageClass=${HARBOR_SC}" \
    --set "persistence.persistentVolumeClaim.jobservice.jobLog.storageClass=${HARBOR_SC}" \
    --set "persistence.persistentVolumeClaim.database.storageClass=${HARBOR_SC}" \
    --set "persistence.persistentVolumeClaim.redis.storageClass=${HARBOR_SC}" \
    --set "externalURL=${HARBOR_URL}" \
    --set "expose.nodePort.ports.http.nodePort=${HARBOR_NODEPORT}" \
    --set "harborAdminPassword=${HARBOR_ADMIN_PASSWORD}" \
    --wait --timeout 20m \
    || die "Harbor did not become ready. Inspect: kubectl -n ${HARBOR_NAMESPACE} get pods"

  info "waiting for the Harbor API on ${HARBOR_URL}"
  local deadline=$((SECONDS + 300))
  while (( SECONDS < deadline )); do
    if curl -fsS --max-time 5 -u "admin:${HARBOR_ADMIN_PASSWORD}" \
         "${HARBOR_URL}/api/v2.0/systeminfo" >/dev/null 2>&1; then
      ok "Harbor is serving at ${HARBOR_URL}"
      umask 077
      printf '%s\n' "${HARBOR_ADMIN_PASSWORD}" > "${OUTPUT_DIR}/harbor-admin-password"
      umask 022
      return 0
    fi
    sleep 5
  done
  die "Harbor's API never answered on ${HARBOR_URL}. Check: kubectl -n ${HARBOR_NAMESPACE} get pods"
}

push_demo_image() {
  local tar="${AIRGAP_DEMO_DIR}/${DEMO_IMAGE_NAME}.tar"
  [[ -f "${tar}" ]] || die "demo image tarball missing: ${tar}"

  info "pushing ${DEMO_IMAGE_NAME}:${DEMO_IMAGE_TAG} into Harbor as ${DEMO_IMAGE_REF}"
  run_logged skopeo copy --quiet \
    --dest-tls-verify=false \
    --dest-creds "admin:${HARBOR_ADMIN_PASSWORD}" \
    "docker-archive:${tar}" \
    "docker://${DEMO_IMAGE_REF}" \
    || die "failed to push the demo image into Harbor"

  # Prove it is really there before asking the cluster to pull it.
  curl -fsS -u "admin:${HARBOR_ADMIN_PASSWORD}" \
    "${HARBOR_URL}/api/v2.0/projects/${HARBOR_PROJECT}/repositories/${DEMO_IMAGE_NAME}/artifacts" \
    >/dev/null || die "Harbor does not list ${DEMO_IMAGE_REF} after the push"
  ok "image available in Harbor project '${HARBOR_PROJECT}'"
}

# --------------------------------------------------------------------------
# stage: demo workload
# --------------------------------------------------------------------------
deploy_demo() {
  local cfg="${STATE_DIR}/node-demo-config"
  rm -rf "${cfg}"; mkdir -p "${cfg}"

  [[ -s "${OUTPUT_DIR}/nodes.tsv" ]] || die "nodes.tsv was not produced by the post-install playbook"

  # One ConfigMap key per Kubernetes node name, holding that machine's facts.
  local idx name ip os kernel arch cpus memory
  while IFS=$'\t' read -r idx name ip os kernel arch cpus memory; do
    [[ -n "${name}" ]] || continue
    {
      echo "index=${idx}"
      echo "ip=${ip}"
      echo "os=${os}"
      echo "kernel=${kernel}"
      echo "arch=${arch}"
      echo "cpus=${cpus}"
      echo "memory=${memory}"
    } > "${cfg}/${name}"
    printf '%s\t%s\thttp://%s:%s/\n' "${idx}" "${name}" "${ip}" "${DEMO_NODEPORT}" >> "${cfg}/peers"
  done < "${OUTPUT_DIR}/nodes.tsv"

  printf '%s' "${CLUSTER_NAME}"    > "${cfg}/cluster-name"
  printf '%s' "${HARBOR_URL}"      > "${cfg}/registry"
  printf '%s' "${DEMO_IMAGE_REF}"  > "${cfg}/image"

  export DEMO_CONFIG_CHECKSUM
  DEMO_CONFIG_CHECKSUM="$(LC_ALL=C find "${cfg}" -type f | sort | xargs cat | sha256sum | cut -c1-16)"

  kubectl create namespace "${DEMO_NAMESPACE}" --dry-run=client -o yaml | kubectl apply -f - >/dev/null

  kubectl -n "${DEMO_NAMESPACE}" create secret docker-registry harbor-pull \
    --docker-server="${HARBOR_HOST}:${HARBOR_NODEPORT}" \
    --docker-username=admin \
    --docker-password="${HARBOR_ADMIN_PASSWORD}" \
    --dry-run=client -o yaml | kubectl apply -f - >/dev/null

  kubectl -n "${DEMO_NAMESPACE}" create configmap node-demo \
    --from-file="${cfg}" --dry-run=client -o yaml | kubectl apply -f - >/dev/null

  export DEMO_NAMESPACE DEMO_IMAGE_REF DEMO_NODEPORT
  envsubst '${DEMO_NAMESPACE} ${DEMO_IMAGE_REF} ${DEMO_NODEPORT} ${DEMO_CONFIG_CHECKSUM}' \
    < /opt/demo/manifests/node-demo.yaml > "${STATE_DIR}/node-demo.yaml"
  cp "${STATE_DIR}/node-demo.yaml" "${OUTPUT_DIR}/node-demo.yaml"

  run_logged kubectl apply -f "${STATE_DIR}/node-demo.yaml" \
    || die "could not apply the demo manifests"

  if [[ -n "${VIP_ADDRESS}" ]]; then
    export INGRESS_CLASS VIP_ADDRESS
    envsubst '${DEMO_NAMESPACE} ${INGRESS_CLASS} ${VIP_ADDRESS}' \
      < /opt/demo/manifests/node-demo-ingress.yaml > "${STATE_DIR}/node-demo-ingress.yaml"
    cp "${STATE_DIR}/node-demo-ingress.yaml" "${OUTPUT_DIR}/node-demo-ingress.yaml"
    run_logged kubectl apply -f "${STATE_DIR}/node-demo-ingress.yaml" \
      || die "could not apply the demo Ingress"
    ok "demo also published through Traefik on http://${VIP_ADDRESS}/"
  fi

  info "waiting for one pod per node to pull ${DEMO_IMAGE_REF} from Harbor"
  run_logged kubectl -n "${DEMO_NAMESPACE}" rollout status daemonset/node-demo --timeout=6m \
    || die "the demo DaemonSet never became ready. Check: kubectl -n ${DEMO_NAMESPACE} describe pods"
  ok "demo workload running on every node"
}

# --------------------------------------------------------------------------
# stage: verify
# --------------------------------------------------------------------------
verify_demo() {
  local failed=0 idx name ip body served
  while IFS=$'\t' read -r idx name ip _rest; do
    [[ -n "${ip}" ]] || continue
    if ! body="$(curl -fsS --max-time 10 "http://${ip}:${DEMO_NODEPORT}/info.json" 2>&1)"; then
      warn "node ${idx} (${ip}) did not answer on port ${DEMO_NODEPORT}"
      failed=1
      continue
    fi
    served="$(jq -r '.nodeName' <<< "${body}" 2>/dev/null || echo '?')"
    if [[ "${served}" == "${name}" ]]; then
      ok "http://${ip}:${DEMO_NODEPORT}/  ->  Node ${idx} (${served})"
    else
      warn "http://${ip}:${DEMO_NODEPORT}/ was answered by '${served}', expected '${name}'"
      failed=1
    fi
  done < "${OUTPUT_DIR}/nodes.tsv"
  (( failed == 0 )) || warn "some nodes did not serve their own page; see the log at ${LOG_FILE}"

  # The ingress is the other half of the story: same DaemonSet, but reached
  # through the VIP and balanced, so repeated calls should not always land on
  # the same node.
  if [[ -n "${VIP_ADDRESS}" ]]; then
    local seen=() answer
    for _ in 1 2 3 4 5 6; do
      answer="$(curl -fsS --max-time 10 "http://${VIP_ADDRESS}/info.json" 2>/dev/null \
                | jq -r '.nodeName' 2>/dev/null || true)"
      [[ -n "${answer}" ]] && seen+=("${answer}")
    done
    if (( ${#seen[@]} == 0 )); then
      warn "http://${VIP_ADDRESS}/ did not answer - check the Traefik ingress and the VIP"
    else
      local distinct
      distinct="$(printf '%s\n' "${seen[@]}" | sort -u | tr '\n' ' ' | sed 's/ $//')"
      ok "http://${VIP_ADDRESS}/  ->  answered by: ${distinct}"
    fi
  fi
}

