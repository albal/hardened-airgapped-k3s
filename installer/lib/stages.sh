run_k3s_install() {
  info "copying $(du -sh "${AIRGAP_K3S_DIR}" | cut -f1) of artifacts to each node - this is the slow part"

  # On a re-run against a live cluster, restarting all three servers at once can
  # cost etcd its quorum. One host at a time is slower but safe; a first install
  # has no cluster to lose, so it keeps the default parallelism.
  local forks=(--forks 5)
  if kubectl get nodes >/dev/null 2>&1; then
    forks=(--forks 1)
    dim "existing cluster detected - applying one node at a time to protect etcd quorum"
  fi

  run_logged ansible-playbook "${forks[@]}" /opt/k3s-ansible/playbooks/site.yml \
    -e "@${STATE_DIR}/vars.yml" \
    || die "k3s installation failed"
  ok "k3s ${K3S_VERSION} installed on ${#NODE_IPS[@]} node(s)"
}

fetch_cluster_access() {
  run_logged ansible-playbook /opt/ansible/playbooks/30-post-install.yml \
    -e "@${STATE_DIR}/vars.yml" \
    || die "could not retrieve the kubeconfig"

  local deadline=$((SECONDS + 300)) ready=0 total="${#NODE_IPS[@]}"
  while (( SECONDS < deadline )); do
    ready="$(kubectl get nodes --no-headers 2>/dev/null \
             | awk '$2 == "Ready" { n++ } END { print n + 0 }')"
    (( ready >= total )) && break
    sleep 5
  done
  (( ready >= total )) || die "only ${ready}/${total} nodes reached Ready. Check 'kubectl get nodes' with ${KUBECONFIG}."
  ok "${ready}/${total} nodes Ready"
  kubectl get nodes -o wide 2>&1 | sed 's/^/      /' | tee -a "${LOG_FILE}"
}

