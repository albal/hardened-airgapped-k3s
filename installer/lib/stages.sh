render_kube_vip() {
  local tmpl="${AIRGAP_KUBE_VIP_DIR}/kube-vip.yaml.tmpl"
  [[ -f "${tmpl}" ]] || die "kube-vip manifest template missing: ${tmpl}"

  # The interface name goes into a DaemonSet, so it has to be valid on every
  # server. Preflight records the common one; an explicit setting overrides it.
  local iface="${VIP_INTERFACE}"
  if [[ -z "${iface}" && -r "${STATE_DIR}/vip-interface" ]]; then
    iface="$(tr -d '[:space:]' < "${STATE_DIR}/vip-interface")"
  fi
  [[ -n "${iface}" ]] || die "could not determine the network interface for the VIP.
     Set K3S_VIP_INTERFACE (e.g. ens18) and run again."

  mkdir -p "${STATE_DIR}/manifests"
  sed -e "s|@@VIP_ADDRESS@@|${VIP_ADDRESS}|g" \
      -e "s|@@VIP_INTERFACE@@|${iface}|g" \
      "${tmpl}" > "${STATE_DIR}/manifests/kube-vip.yaml"

  if grep -q '@@' "${STATE_DIR}/manifests/kube-vip.yaml"; then
    die "unsubstituted placeholder left in the kube-vip manifest"
  fi
  # There is no cluster to validate against yet - even --dry-run=client needs one
  # to resolve resource kinds - so check the manifest offline instead: it must
  # parse as YAML and contain the four objects kube-vip needs to run.
  python3 - "${STATE_DIR}/manifests/kube-vip.yaml" <<'PY' \
    || die "the rendered kube-vip manifest is not usable - see the error above"
import sys, yaml
docs = [d for d in yaml.safe_load_all(open(sys.argv[1])) if d]
kinds = sorted(d.get("kind", "?") for d in docs)
want = ["ClusterRole", "ClusterRoleBinding", "DaemonSet", "ServiceAccount"]
missing = [k for k in want if k not in kinds]
if missing:
    sys.exit(f"kube-vip manifest is missing {', '.join(missing)} (found: {', '.join(kinds)})")
ds = next(d for d in docs if d.get("kind") == "DaemonSet")
env = {e["name"]: e.get("value") for e in
       ds["spec"]["template"]["spec"]["containers"][0].get("env", [])}
for key in ("address", "vip_interface"):
    if not env.get(key):
        sys.exit(f"kube-vip DaemonSet has no {key} set")
print(f"  {len(docs)} objects, address={env['address']} interface={env['vip_interface']}")
PY

  ok "kube-vip ${KUBE_VIP_VERSION} manifest rendered for ${VIP_ADDRESS} on ${iface}"
  dim "k3s applies it from its manifests directory as soon as the API is up"
}

verify_vip() {
  info "waiting for the API to answer on ${VIP_ADDRESS}"
  local deadline=$((SECONDS + 240)) code=
  while (( SECONDS < deadline )); do
    # Any HTTP answer proves the API is reachable through the VIP. k3s requires
    # authentication for /readyz, so it replies 401 rather than "ok" - checking
    # for the body text reports a perfectly working VIP as broken.
    code="$(curl -sk --max-time 5 -o /dev/null -w '%{http_code}' \
            "https://${VIP_ADDRESS}:6443/version" 2>/dev/null || true)"
    if [[ "${code}" =~ ^(200|401|403)$ ]]; then
      ok "API server reachable on the VIP"
      run_logged kubectl -n kube-system rollout status daemonset/kube-vip-ds --timeout=120s \
        || warn "kube-vip is serving the VIP but its DaemonSet is not fully rolled out"
      return 0
    fi
    sleep 5
  done

  # The cluster itself is fine - only the VIP is not up. Degrade loudly rather
  # than throwing away a working install.
  warn "the VIP ${VIP_ADDRESS} never answered on :6443."
  warn "The cluster is up; kubectl still works against ${NODE_IPS[0]}."
  warn "Check: kubectl -n kube-system get pods -l app.kubernetes.io/name=kube-vip-ds"
  return 0
}

