# stage: summary
# --------------------------------------------------------------------------
write_summary() {
  local summary="${OUTPUT_DIR}/SUMMARY.md" nodes_md=""
  local idx name ip os _rest
  while IFS=$'\t' read -r idx name ip os _rest; do
    [[ -n "${ip}" ]] || continue
    nodes_md+="| ${idx} | \`${name}\` | ${ip} | ${os} | <http://${ip}:${DEMO_NODEPORT}/> |"$'\n'
  done < "${OUTPUT_DIR}/nodes.tsv"

  local VIP_SUMMARY
  if [[ -n "${VIP_ADDRESS}" ]]; then
    VIP_SUMMARY="\`${VIP_ADDRESS}\` floats between the servers (kube-vip, ARP mode) and serves
the API on :6443, Traefik on :80/:443 and Harbor on :${HARBOR_NODEPORT}. Losing the node
that currently holds it moves the address rather than the service.

The nodes still join through \`${NODE_IPS[0]}\` when k3s is installed, so keep that
address reachable if you re-run the installer."
  else
    VIP_SUMMARY="Not configured, so services are reached per node and \`${NODE_IPS[0]}\` is a
single point of failure for new image pulls. Re-run with \`--vip <address>\` to put
one stable address in front of the API, the ingress and the registry."
  fi

  cat > "${summary}" <<MD
# ${CLUSTER_NAME}

Installed $(date -u '+%Y-%m-%d %H:%M UTC') by the airgapped installer.

## Nodes

| # | Node | IP | OS | Demo page |
|---|------|----|----|-----------|
${nodes_md}
## Virtual IP

${VIP_SUMMARY}

## Harbor

- URL: <${HARBOR_URL}>
- User: \`admin\`
- Password: see \`harbor-admin-password\` next to this file
- Demo image: \`${DEMO_IMAGE_REF}\`

Push your own images from a machine that can reach the registry:

\`\`\`sh
docker login ${HARBOR_HOST}:${HARBOR_NODEPORT}      # admin / <password>
docker tag myapp:1.0 ${HARBOR_HOST}:${HARBOR_NODEPORT}/${HARBOR_PROJECT}/myapp:1.0
docker push ${HARBOR_HOST}:${HARBOR_NODEPORT}/${HARBOR_PROJECT}/myapp:1.0
\`\`\`

Harbor is served over plain HTTP, so add it to the pushing client's insecure
registry list (\`/etc/docker/daemon.json\`: \`{"insecure-registries":["${HARBOR_HOST}:${HARBOR_NODEPORT}"]}\`).
Every k3s node is already configured for it via \`/etc/rancher/k3s/registries.yaml\`.

## Cluster access

\`\`\`sh
export KUBECONFIG=\$PWD/kubeconfig
kubectl get nodes -o wide
kubectl -n ${DEMO_NAMESPACE} get pods -o wide
\`\`\`

The kubeconfig points at \`${CLUSTER_ENDPOINT}\`.

k3s runs with embedded etcd across all ${#NODE_IPS[@]} servers and
\`secrets-encryption\` enabled.

## Storage

Longhorn is the default StorageClass, replicating every volume across the nodes'
data disks. k3s's \`local-path\` is still installed but no longer the default, so
a PVC that names no class gets replicated storage.

Harbor's volumes are on \`${HARBOR_SC}\`. A PVC's class cannot be changed once it
has bound, so moving an existing Harbor to a different class means deleting its
volumes first.

\`\`\`sh
kubectl get storageclass
kubectl -n ${LONGHORN_NAMESPACE} get nodes.longhorn.io
\`\`\`
MD

  {
    echo "CLUSTER_NAME=${CLUSTER_NAME}"
    echo "NODE_IPS=${NODE_IPS[*]}"
    echo "HARBOR_URL=${HARBOR_URL}"
    echo "DEMO_IMAGE_REF=${DEMO_IMAGE_REF}"
    echo "DEMO_URL_TEMPLATE=http://<node-ip>:${DEMO_NODEPORT}/"
    echo "VIP_ADDRESS=${VIP_ADDRESS}"
    echo "CLUSTER_ENDPOINT=${CLUSTER_ENDPOINT}"
    echo "HARBOR_STORAGE_CLASS=${HARBOR_SC}"
  } > "${OUTPUT_DIR}/cluster.env"

  printf '\n'
  rule
  printf '      %sCluster is up.%s\n\n' "${C_GREEN}${C_BOLD}" "${C_RESET}"
  if [[ -n "${VIP_ADDRESS}" ]]; then
    info "VIP       ${VIP_ADDRESS}  (api :6443, ingress :80, harbor :${HARBOR_NODEPORT})"
  fi
  info "Harbor    ${HARBOR_URL}  (admin / $(cat "${OUTPUT_DIR}/harbor-admin-password"))"
  info "Storage   longhorn (default) · harbor on ${HARBOR_SC}"
  info "Demo      http://<node-ip>:${DEMO_NODEPORT}/"
  info "kubeconfig, summary and logs are in the output directory on the host"
  rule
}

# --------------------------------------------------------------------------
# stage: reset
# --------------------------------------------------------------------------
run_reset() {
  warn "this uninstalls k3s and destroys all cluster data on: ${NODE_IPS[*]}"
  if [[ -z "${ASSUME_YES:-}" ]]; then
    confirm "Really uninstall k3s from these machines?" || die "aborted - nothing was changed"
  fi
  run_logged ansible-playbook /opt/k3s-ansible/playbooks/reset.yml \
    -e "@${STATE_DIR}/vars.yml" \
    || die "reset failed"
  ok "k3s removed from all nodes"
}
